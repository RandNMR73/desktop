const done=arguments[arguments.length-1];
(async()=>{
  if (!Services.dirsvc.get('ProfD',Ci.nsIFile).path.includes('zen-search-color-retention-')) throw Error('Disposable fixture required');
  const w=Services.wm.getMostRecentWindow('navigator:browser');
  await w.gZenWorkspaces.promiseInitialized;
  const checks=[],tabs=[];
  const check=(name,pass)=>{checks.push({name,passed:!!pass});if(!pass)throw Error(name)};
  const pause=(ms=120)=>new Promise(r=>w.setTimeout(r,ms));
  const custom='data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><rect width="32" height="32" fill="#8060d0"/></svg>');
  const manager=w.gZenPinnedTabManager,sync=w.gZenWindowSync,root=w.document.documentElement;
  const style=t=>w.getComputedStyle(t.querySelector('.tab-icon-image'));
  const expected=(id,appearance)=>`url("chrome://browser/content/zen-images/favicons/app-tray/${id}-${appearance}.svg")`;
  root.setAttribute('zen-should-be-dark-mode','false');
  for(const [id,url] of [['twitter','https://twitter.com/'],['gmail','https://mail.google.com/'],['spotify','https://open.spotify.com/'],['youtube','https://youtube.com/'],['whatsapp','https://web.whatsapp.com/']]){
    const tab=w.gBrowser.addTrustedTab('about:blank',{skipAnimation:true});
    for(let i=0;i<50&&!tab.id;i++)await pause();
    manager.addToEssentials(tab);await pause(500);
    tab.label=id;
    sync.setPinnedInitialState(tab,{url,title:id},custom);
    tab.setAttribute('image','chrome://global/skin/icons/info.svg');manager.setEssentialTabIcon(tab);await pause();
    check(id+' light artwork and 40pt box',style(tab).content===expected(id,'light')&&style(tab).width==='40px'&&style(tab).height==='40px');
    check(id+' keeps underlying favicon and pinned state',tab.getAttribute('image').endsWith('/info.svg')&&tab._zenPinnedInitialState.image===custom&&!tab.zenStaticIcon);
    const image=new w.Image();const loaded=new Promise((resolve,reject)=>{image.onload=resolve;image.onerror=reject});image.src=JSON.parse(style(tab).content.slice(4,-1));await loaded;
    check(id+' bundled artwork decodes',image.naturalWidth===40&&image.naturalHeight===40);
    tabs.push(tab);
  }
  root.setAttribute('zen-should-be-dark-mode','true');await pause();
  for(const tab of tabs)check(tab.label+' dark artwork',style(tab).content===expected(tab.getAttribute('zen-favorite-app-icon'),'dark'));
  const twitter=tabs[0];w.gBrowser.selectedTab=twitter;
  for(let i=0;i<40&&!twitter.hasAttribute('zen-favorite-outline-ready');i++)await pause();
  check('dark selected outline renders',twitter.hasAttribute('zen-favorite-outline-ready'));
  const darkOutline=twitter.style.getPropertyValue('--zen-favorite-outline-image');
  root.setAttribute('zen-should-be-dark-mode','false');await pause();
  for(let i=0;i<40&&!twitter.hasAttribute('zen-favorite-outline-ready');i++)await pause();
  check('appearance change refreshes selected outline without switching tabs',twitter.hasAttribute('zen-favorite-outline-ready')&&twitter.style.getPropertyValue('--zen-favorite-outline-image')!==darkOutline);
  twitter.zenStaticIcon=custom;manager.setEssentialTabIcon(twitter);await pause();
  check('custom icon wins and returns to 16pt',style(twitter).content===`url("${custom}")`&&style(twitter).width==='16px'&&!twitter.hasAttribute('zen-favorite-app-icon'));
  delete twitter.zenStaticIcon;manager.setEssentialTabIcon(twitter);await pause();
  check('removing custom icon restores app artwork',style(twitter).content===expected('twitter','light'));
  const youtube=tabs[3];
  sync.setPinnedInitialState(youtube,{url:'https://music.youtube.com/',title:'Music'},custom);await pause();
  check('YouTube Music keeps saved site artwork at 16pt',!youtube.hasAttribute('zen-favorite-app-icon')&&style(youtube).content===`url("${custom}")`&&style(youtube).width==='16px');
  sync.setPinnedInitialState(youtube,{url:'https://youtube.com/',title:'YouTube'},custom);await pause();
  check('saved destination changes restore YouTube artwork',style(youtube).content===expected('youtube','light'));
  const gmail=tabs[1];
  sync.setPinnedInitialState(gmail,{url:'https://mail.google.com/chat/',title:'Chat'},custom);await pause();
  check('Gmail Chat keeps site artwork',!gmail.hasAttribute('zen-favorite-app-icon')&&style(gmail).width==='16px');
  sync.setPinnedInitialState(gmail,{url:'https://accounts.google.com/?continue=https%3A%2F%2Fmail.google.com%2Fmail',title:'Gmail'},custom);await pause();
  check('Google account redirect resolves Gmail artwork',style(gmail).content===expected('gmail','light'));
  const next=w.OpenBrowserWindow();
  for(let i=0;i<100&&!next.gZenWorkspaces?.promiseInitialized;i++)await pause();
  await next.gZenWorkspaces.promiseInitialized;await next.gZenStartup.promiseInitialized;
  for(let i=0;i<80&&!next.document.getElementById(youtube.id);i++)await pause();
  const twin=next.document.getElementById(youtube.id);
  check('second window restores app artwork',twin?.getAttribute('zen-favorite-app-icon')==='youtube');
  sync.setPinnedInitialState(youtube,{url:'https://music.youtube.com/',title:'Music'},custom);await pause();
  check('saved URL change refreshes artwork in both windows',!youtube.hasAttribute('zen-favorite-app-icon')&&!twin.hasAttribute('zen-favorite-app-icon'));
  next.close();
  sync.setPinnedInitialState(youtube,{url:'https://youtube.com/',title:'YouTube'},custom);await pause();
  return {passed:true,checks,productionProfileUsed:false,fixtureTabIDs:tabs.map(t=>t.id)};
})().then(done,error=>done({passed:false,error:String(error),stack:error.stack}));
