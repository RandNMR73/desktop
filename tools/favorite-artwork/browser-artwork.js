  const pause=()=>new Promise(r=>w.setTimeout(r,120));
  const svg=color=>'data:image/svg+xml,'+encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><rect width="32" height="32" rx="5" fill="${color}"/></svg>`);
