const done=arguments[arguments.length-1];
(async()=>{
 const w=Services.wm.getMostRecentWindow('navigator:browser'),d=w.document;
 const {Downloads}=ChromeUtils.importESModule('resource://gre/modules/Downloads.sys.mjs');
 const button=d.getElementById('zen-library-button'),list=d.getElementById('zen-library-download-list'),foot=d.getElementById('zen-sidebar-foot-buttons');
 const pause=ms=>new Promise(r=>w.setTimeout(r,ms)),open=()=>foot.hasAttribute('zen-library-stack-open');
 const center=n=>{const r=n.getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}};
 const event=(n,type,p)=>n.dispatchEvent(new w.MouseEvent(type,{clientX:p.x,clientY:p.y}));
 const enter=()=>event(button,'mouseenter',center(button)),leave=()=>event(button,'mouseleave',{x:400,y:400});
 const until=async fn=>{for(let i=0;i<100&&!fn();i++)await pause(10)};
 const motion=n=>n.getAnimations().find(a=>a.effect.getKeyframes().some(k=>k.transform));
 const rect=n=>JSON.parse(JSON.stringify(n.getBoundingClientRect()));
 let checks=0;const failures=[],traces=[];const check=(ok,msg)=>{checks++;if(!ok)failures.push(msg)};
 enter();await until(open);await pause(450);leave();await pause(400);
 const fixture=[...list.children].find(n=>!n.hidden).download;
 const downloads=await Downloads.getList(Downloads.PUBLIC);
 const add=async()=>{const x=await Downloads.createDownload({...fixture,source:{url:'https://example.invalid/owned-badge-fixture'},startTime:new Date(),endTime:Date.now()});await x.refresh();await downloads.add(x);await pause(60);return x};
 let download=await add();
 try {
  const footer=d.getElementById('library-button-badge'),closed=rect(footer),bc=center(button);
  check(foot.hasAttribute('zen-library-badge'),'new completed download shows footer badge');
  check(Math.abs(closed.width-22)<.02&&Math.abs(closed.height-22)<.02,'closed badge measures 22pt');
  check(Math.abs(closed.x+11-bc.x-10)<.02&&Math.abs(closed.y+11-bc.y+12)<.02,'native closed center is button center +10,-12');
  enter();await until(open);
  const row=[...list.children].find(n=>n.download?.target.path===download.target.path); if(!row) return {checks,failures,missing:download.toSerializable(),rows:[...list.children].map(n=>({hidden:n.hidden,path:n.download?.target.path})),footer:closed}; const icon=row.querySelector('.zen-library-download-badge'),title=row.querySelector('.zen-library-download-list-title-container');
  const animations=[motion(row),motion(title),motion(row.querySelector('.zen-library-download-action'))];
  check(animations.every(Boolean),'badge row and inserted details use compositor animations');
  check(!foot.hasAttribute('zen-library-badge'),'completed badge is consumed on opening');
  for(const a of animations){a.pause();a.currentTime=0}
  await w.promiseDocumentFlushed(()=>true);
  const initial=rect(icon);check(Math.abs(initial.x-closed.x)<.03&&Math.abs(initial.y-closed.y)<.03&&Math.abs(initial.width-22)<.03,'row begins at actual footer badge without a jump');
  const native=t=>{const o=2*Math.PI/.15,a=o*.86,b=o*Math.sqrt(1-.86*.86);return 1-Math.exp(-a*t)*(Math.cos(b*t)+a/b*Math.sin(b*t))};
  const sidebar=d.getElementById('navigator-toolbox').getBoundingClientRect().width;
  for(const a of animations)a.currentTime=50;
  await w.promiseDocumentFlushed(()=>true);
  const at50=rect(icon),p=native(.05),s=.55+.45*p,k=.45*(Math.min(sidebar,1000)-64)/2;
  const endX=closed.x+11-6,endY=closed.y+11-30;
  check(Math.abs(at50.x+at50.width/2-(endX+6*(1-p)+k*p*(1-p)))<.03,'rendered badge X matches native layout curve at 50ms');
  check(Math.abs(at50.y+at50.height/2-(endY+30*(1-p)))<.03,'rendered badge Y matches native spring at 50ms');
  check(Math.abs(at50.width-40*s)<.03,'rendered scale matches native spring at 50ms');
  check(Math.abs(Number(w.getComputedStyle(title).opacity)-p)<.001,'details insert with native fade');
  for(const a of animations)a.finish();await pause(50);
  const expanded=rect(icon);check(Math.abs(expanded.width-40)<.02,'expanded badge measures 40pt');
  leave();await pause(400);check(!foot.hasAttribute('zen-library-badge'),'consumed badge stays absent on close');
  traces.push({closed,initial,at50,expanded,sidebar});
  await downloads.remove(download);download=await add();
  enter();await until(open);await pause(45);
  const moving=[...list.children].find(n=>n.download?.target.path===download.target.path),before=motion(moving),age=d.timeline.currentTime-before.startTime;
  const beforeStyle=new w.DOMMatrix(w.getComputedStyle(moving).transform);
  leave();const closing=motion(moving),first=new w.DOMMatrix(closing.effect.getKeyframes()[0].transform);
  check(Math.abs(first.a-beforeStyle.a)<.005&&Math.abs(first.e-beforeStyle.e)<.15&&Math.abs(first.f-beforeStyle.f)<.15,'interrupted close retains presentation position and scale');
  const end=new w.DOMMatrix(closing.effect.getKeyframes().at(-1).transform);
  check(end.a===1&&end.f===20,'interrupted completed badge closes as an ordinary row');
  check(Number(closing.effect.getKeyframes().at(-1).opacity)===0,'interrupted badge fades away');
  enter();await until(open);leave();await pause(400);
  check(!open()&&!foot.hasAttribute('zen-library-stack-closing'),'rapid re-entry finishes cleanly');
  traces.push({interruptionAgeMs:age});
 } finally {await downloads.remove(download)}
 return{checks,failures,traces,production_profile_used:false};
})().then(done,e=>done({error:String(e),stack:e.stack}));
